import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# Define variables
L = 6
R_A = 170
R_B = 410
q_1 = 120
P_1 = 100
q_2 = 120

# Create x values
x = np.linspace(0, L, 500)

# Create an array of zeros for V
V = np.zeros_like(x)

# Calculate shear values
for i in range(len(x)):
    if x[i] < 2:
        V[i] = R_A - (q_1 * x[i])
    elif x[i] < 4:
        V[i] = R_A - (q_1 * 2) - P_1
    else:
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (x[i] - 4))

# Plot the shear diagram
plt.figure(figsize = (10, 6))
plt.plot(x, V, label = 'Shear Force')

# Shade the area
plt.fill_between(x, V, 0, alpha = 0.3)

# Add vertical jumps
plt.vlines(2, -70, -170)
plt.vlines(4, -170, 240)

# Add labels and title
plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')

# Add horizontal axis
plt.axhline(0, color = 'black')

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Define variables
L = 6
R_A = 170
R_B = 410
q_1 = 120
P_1 = 100
q_2 = 120

# Create x values
x = np.linspace(0, L, 500)

# Create an array of zeros for M
M = np.zeros_like(x)

# Calculate moment values
for i in range(len(x)):
    if x[i] < 2:
        M[i] = (R_A * x[i]) - (q_1 * x[i]**2 / 2)
    elif x[i] < 4:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2))
    else:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2)) + (R_B * (x[i] - 4)) - (q_2 * (x[i] - 4) * ((x[i] - 4) / 2))

# Plot the moment diagram
plt.figure(figsize=(10, 6))
plt.plot(x, M, label = 'Bending Moment')

# Shade the area
plt.fill_between(x, M, 0, alpha=0.3)

# Add labels and title
plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')

# Add horizontal axis
plt.axhline(0, color = 'black')

plt.show()

