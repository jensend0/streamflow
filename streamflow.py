plt.ylabel("Births")

# I used AI to help find the local minimuns and do the annotations properly
# Programmatically finding the exact local minima (dips) near each holiday to guarantee accurate arrow alignment
# 1. New Year's Day (around Jan 1)
idx_ny = np.argmin(y_1[0:3])
# 2. Independence Day (around July 4, which is day 186 in leap year 2012, index ~ 185)
idx_july4 = 181 + np.argmin(y_1[181:188])
# 3. Halloween (around Oct 31, index 304 in leap year 2012)
idx_halloween = 301 + np.argmin(y_1[301:307])
# 4. Thanksgiving (Nov 22, 2012, index 326)
idx_thanksgiving = 323 + np.argmin(y_1[323:330])
# 5. Christmas Day (Dec 25, index 359 in leap year 2012)
idx_christmas = 356 + np.argmin(y_1[356:362])

# Add holiday annotations targeting the exact dips
plt.annotate("New Year's Day",
             xy=(x[idx_ny], y_1[idx_ny]),
             xytext=(x[idx_ny + 15], y_1[idx_ny] - 200),
             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=-0.3"))

plt.annotate("4th of July",
             xy=(x[idx_july4], y_1[idx_july4]),
             xytext=(x[idx_july4 + 15], y_1[idx_july4] - 100),
             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=0.3"))

plt.annotate("Halloween",
             xy=(x[idx_halloween], y_1[idx_halloween]),
             xytext=(x[idx_halloween - 30], y_1[idx_halloween] + 150),
             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=-0.3"))

plt.annotate("Thanksgiving",
             xy=(x[idx_thanksgiving], y_1[idx_thanksgiving]),
             xytext=(x[idx_thanksgiving - 35], y_1[idx_thanksgiving] - 200),
             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=0.3"))

